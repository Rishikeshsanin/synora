"""Original illustrated same-SKU views for deterministic, offline CI."""
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def main(directory):
    root = Path(directory)
    root.mkdir(parents=True, exist_ok=True)
    shots = []
    for i, role in enumerate(('hero', 'detail', 'context')):
        image = Image.new('RGB', (900, 900), ('#ded0bc', '#b2c5bb', '#b9bdce')[i])
        draw = ImageDraw.Draw(image)
        x, y, w, h = ((310, 180, 280, 560), (235, 90, 430, 720), (460, 290, 220, 440))[i]
        draw.ellipse((x-65, y+h-20, x+w+65, y+h+45), fill='#86877d')
        draw.rounded_rectangle((x, y, x+w, y+h), radius=35, fill='#193b40')
        draw.rounded_rectangle((x+w//4, y-55, x+3*w//4, y+45), radius=16, fill='#142b30')
        draw.rounded_rectangle((x+15, y+h//3, x+w-15, y+2*h//3), radius=10, fill='#e9dfc9')
        draw.text((x+w//2, y+h//2), 'AUREL DEMO', font=ImageFont.load_default(size=w//9), anchor='mm', fill='#193b40')
        if role == 'context':
            draw.ellipse((100, 620, 300, 710), fill='#d7b28a')
            draw.ellipse((135, 635, 265, 690), fill='#584637')
        path = root/f'{role}.png'
        image.save(path)
        shots.append(dict(path=str(path.resolve()), product_id='aurel-demo', role=role,
                          source='original fictional illustration generated by campaign_fixture.py', rights_confirmed=True))
    manifest = dict(brief=dict(audience='young adults', occasion='launch', goal='awareness', industry='retail', emotion='excited', platform='reels'),
                    collection=False, audio_rights_confirmed=True, shots=shots)
    (root/'manifest.json').write_text(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    main(sys.argv[1])
